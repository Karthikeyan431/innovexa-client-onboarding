// Embeds the binary assets used by the PDF generator (Inter fonts and the
// Innovexa logo mark) as base64 modules, so serverless bundles never depend on
// reading files from disk at runtime. Run after changing any of them.
import { readFileSync, writeFileSync } from 'node:fs';

const b64 = (path) => readFileSync(new URL(`../${path}`, import.meta.url)).toString('base64');
const write = (path, body) => {
  writeFileSync(new URL(`../${path}`, import.meta.url), `// Generated by scripts/embed-assets.mjs — do not edit.\n${body}`);
  console.log(`wrote ${path}`);
};

write(
  'server/fonts/fonts.generated.ts',
  `// Inter, SIL Open Font License (see OFL.txt).\n` +
    `export const INTER_REGULAR = '${b64('server/fonts/Inter_400Regular.ttf')}';\n` +
    `export const INTER_BOLD = '${b64('server/fonts/Inter_700Bold.ttf')}';\n`,
);
write(
  'server/brand.generated.ts',
  `// Innovexa Digital logo mark (from brand-src/logo-mark-pdf.png).\n` +
    `export const LOGO_MARK_PNG = '${b64('brand-src/logo-mark-pdf.png')}';\n`,
);
