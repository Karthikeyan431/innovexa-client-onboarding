// Embeds the Inter TTFs used by the PDF generator as base64 so serverless
// bundles never depend on reading font files from disk at runtime.
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../server/fonts/', import.meta.url);
const b64 = (f) => readFileSync(new URL(f, dir)).toString('base64');
writeFileSync(
  new URL('fonts.generated.ts', dir),
  `// Generated by scripts/embed-fonts.mjs — do not edit. Inter, SIL Open Font License (see OFL.txt).\n` +
    `export const INTER_REGULAR = '${b64('Inter_400Regular.ttf')}';\n` +
    `export const INTER_BOLD = '${b64('Inter_700Bold.ttf')}';\n`,
);
console.log('wrote server/fonts/fonts.generated.ts');
